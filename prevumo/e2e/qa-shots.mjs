// Screenshot walk of the scripted demo path. Usage: node e2e/qa-shots.mjs <baseUrl> <outDir> [width] [height]
import { chromium } from "@playwright/test";

const [base = "http://localhost:5181", out = "shots", w = "1440", h = "900"] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const page = await browser.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 1, timezoneId: process.env.QA_TIME ? "America/Toronto" : undefined });
// QA_TIME pins the browser clock (for example 2026-10-22T14:18:00-04:00), so screenshots show a realistic day.
if (process.env.QA_TIME) await page.clock.install({ time: new Date(process.env.QA_TIME) });
const errors = [];
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
page.on("pageerror", (e) => errors.push(String(e)));
let n = 0;
const shot = async (name) => page.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-${name}.png` });
const demo = async () => {
  await page.keyboard.press("Shift+D");
  await page.getByRole("complementary", { name: "Demo controls" }).waitFor();
};

await page.goto(`${base}/login`);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForTimeout(1200);
await shot("login");
await page.getByRole("button", { name: "Log in" }).click();
await page.waitForURL("**/locations");
await page.waitForTimeout(600);
await shot("locations");
await page.getByRole("link", { name: /Makerspace 1/ }).first().click();
await page.waitForTimeout(2500);
await shot("home");
await demo();
await shot("demo-panel");
await page.getByRole("button", { name: "Trigger irregularity" }).click();
await page.waitForTimeout(5000);
await shot("banner");
await page.getByRole("button", { name: "Review" }).first().click();
await page.waitForTimeout(800);
await shot("alert-modal");
await page.getByRole("button", { name: "Call technician" }).click();
await page.waitForTimeout(700);
await shot("tech-panel");
await page.getByRole("button", { name: "Send request" }).click();
await page.waitForTimeout(700);
await shot("tech-sent");
await page.getByRole("button", { name: "Done" }).click();
await page.waitForTimeout(600);
await shot("home-after-tech");
await demo();
await page.getByRole("button", { name: /Trigger idle/ }).click();
await page.waitForTimeout(2500);
await shot("idle-prompt");
await page.getByRole("alertdialog").getByRole("button", { name: "Shut down" }).click();
await page.waitForTimeout(1200);
await shot("shutting-down");
await page.waitForTimeout(2600);
await shot("after-shutdown");
await page.getByRole("switch", { name: "Show all machines" }).click();
await page.waitForTimeout(600);
await shot("show-all");
await page.getByRole("link", { name: /Laser cutter/ }).first().click();
await page.waitForTimeout(1500);
await shot("laser-detail");
await page.getByRole("button", { name: "Assign user" }).first().click();
await page.waitForTimeout(500);
await page.getByLabel("Name or company").fill("Beta Inc.");
await page.getByRole("button", { name: "This afternoon" }).click();
await shot("assign-form");
await page.getByRole("button", { name: "Save assignment" }).click();
await page.waitForTimeout(800);
await shot("assign-saved");
await page.goto(`${base}/l/ms1/m/ms1-welder-2`);
await page.waitForTimeout(2000);
await shot("welder-detail");
await page.mouse.wheel(0, 900);
await page.waitForTimeout(500);
await shot("welder-detail-history");
await demo();
await page.getByRole("button", { name: /Fast forward/ }).click();
await page.waitForTimeout(1500);
await shot("daily-report");
await page.emulateMedia({ media: "print" });
await page.pdf({ path: `${out}/report.pdf`, format: "A4", printBackground: true });
await shot("report-print");
await page.emulateMedia({ media: "screen" });
await page.goto(`${base}/l/ms1/notifications`);
await page.waitForTimeout(800);
await shot("notifications");
await page.goto(`${base}/l/ms1/assignments`);
await page.waitForTimeout(600);
await shot("assignments");
await page.goto(`${base}/l/ms1/settings`);
await page.waitForTimeout(600);
await shot("settings");
await page.goto(`${base}/l/chem`);
await page.waitForTimeout(1500);
await shot("chem-home");
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
console.log(JSON.stringify({ errors, overflow }));
await browser.close();
